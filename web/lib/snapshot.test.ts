import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, test, vi } from "vitest";
import { decodeFrame, loadDay, loadIndex } from "./replay";

const python = process.env.DOWNWIND_TEST_PYTHON;
const pipeline = fileURLToPath(new URL("../../pipeline/", import.meta.url));

test.skipIf(!python)("the browser loader decodes a snapshot generated by Python", async () => {
  const out = mkdtempSync(join(tmpdir(), "downwind-test-"));
  try {
    execFileSync(python!, ["-c", `
import json
from pathlib import Path
import sys
from unittest.mock import patch

import numpy as np
import pandas as pd

from dw.export import export_day, write_index
from dw.rank import run_day
from tests.conftest import T0, flat_met, one_fire, toy_grids

out = Path(sys.argv[1])
yesterday = T0 - pd.Timedelta(days=1)
fires = pd.concat([one_fire(yesterday, 0, 109.07), one_fire(yesterday, 0, 109.37)])
grids = toy_grids(0, 109.07, 100_000)
with patch("dw.tiers.peat_at", side_effect=lambda lat, lon: np.ones(len(lat), dtype=bool)):
    result = run_day(T0, fires, flat_met(0, 0, 0), grids, record_frames=True)
export_day(result, None, None, {"text": "", "source": "template", "model": None}, out, persistence_weighted=False)
lat, lon, _, fire = result.frames[1]
(out / "expected-frame.json").write_text(json.dumps({
    "lat": lat.tolist(), "lon": lon.tolist(), "fire": fire.tolist()
}), encoding="utf-8")
date = T0.date().isoformat()
write_index([date], date, out)
`, out], { cwd: pipeline, timeout: 30_000 });

    vi.stubGlobal("fetch", async (url: string) => {
      expect(url).toMatch(/^\/replay\//);
      return new Response(new Uint8Array(readFileSync(join(out, url.slice("/replay/".length)))));
    });

    const index = await loadIndex();
    const { day, bin } = await loadDay(index.default);
    expect(day.date).toBe("2026-10-22");
    expect(day.fires_date).toBe("2026-10-21");
    expect(day.persistence_weighted).toBe(false);
    expect(day.frames).toHaveLength(48);
    expect(day.fires).toHaveLength(2);
    expect(day.frames[1].offset).toBeGreaterThan(0);
    const frame = decodeFrame(bin, day.frames[1]);
    const expected = JSON.parse(readFileSync(join(out, "expected-frame.json"), "utf-8"));
    expect(new Set(frame.fire)).toEqual(new Set([0, 1]));
    expect(Array.from(frame.fire)).toEqual(expected.fire);
    for (let index = 0; index < frame.fire.length; index++) {
      expect(Math.abs(frame.positions[2 * index] - expected.lon[index])).toBeLessThan(0.0002);
      expect(Math.abs(frame.positions[2 * index + 1] - expected.lat[index])).toBeLessThan(0.0002);
      expect(frame.alpha[index]).toBeGreaterThan(0);
    }
  } finally {
    vi.unstubAllGlobals();
    rmSync(out, { recursive: true, force: true });
  }
}, 35_000);
